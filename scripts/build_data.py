"""Bundle the CEO Signal data into data/site-data.js.

Reads data/companies.json, data/profiles/*.json and data/vocab.json, applies the
standard vocabulary (university names, field-of-study groups, degree levels) and
writes window.CEO_DATA for the website. The site works on GitHub Pages and when
index.html is opened directly from disk.

Run from the repo root:  python scripts/build_data.py
"""
import json
import pathlib
import re
from collections import Counter
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

companies = json.loads((DATA / "companies.json").read_text(encoding="utf-8"))
vocab = json.loads((DATA / "vocab.json").read_text(encoding="utf-8"))

aliases = vocab["institution_aliases"]
field_groups = vocab["field_groups"]
degree_levels = [(d["level"], re.compile(d["pattern"])) for d in vocab["degree_levels"]]
degree_field_groups = vocab.get("degree_field_groups", {})

unmatched_fields = Counter()
institutions = Counter()


def degree_level(degree):
    if not degree:
        return None
    key = re.sub(r"[.\s]", "", degree).upper() if len(degree) < 12 else degree.upper()
    for level, pattern in degree_levels:
        if pattern.search(key):
            return level
    return "Other"


def groups_for_field(field):
    if not field:
        return []
    text = field.lower()
    found = [g["group"] for g in field_groups if any(k in text for k in g["keywords"])]
    if not found:
        unmatched_fields[field] += 1
    return found


def normalize(profile):
    for edu in profile.get("education", []):
        inst = (edu.get("institution") or "").strip()
        edu["institution"] = aliases.get(inst, inst)
        institutions[edu["institution"]] += 1
        edu["degree_level"] = degree_level(edu.get("degree"))
        groups = groups_for_field(edu.get("field"))
        extra = degree_field_groups.get(edu["degree_level"])
        if extra and extra not in groups:
            groups.append(extra)
        edu["field_groups"] = groups
    # internal review notes stay out of the public site
    for key in ("open_issues", "needs_enrichment"):
        profile.pop(key, None)
    return profile


known_ids = {c["id"] for c in companies["companies"]}
profiles = {}
for path in sorted((DATA / "profiles").glob("*.json")):
    profile = normalize(json.loads(path.read_text(encoding="utf-8")))
    cid = profile["company_id"]
    if cid not in known_ids:
        raise SystemExit(f"{path.name}: company_id '{cid}' not in companies.json")
    profiles.setdefault(cid, []).append(profile)

bundle = {
    "built": date.today().isoformat(),
    "list": companies["list"],
    "checked": companies.get("generated"),
    "companies": companies["companies"],
    "profiles": profiles,  # company_id -> list of CEO profiles (2 for co-CEOs)
}

out = DATA / "site-data.js"
out.write_text(
    "// Generated by scripts/build_data.py - do not edit by hand.\n"
    "window.CEO_DATA = " + json.dumps(bundle, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)

people = sum(len(v) for v in profiles.values())
print(f"Wrote {out.relative_to(ROOT)}: {len(companies['companies'])} companies, "
      f"{len(profiles)} with profiles, {people} CEOs, {len(institutions)} universities")
missing = sorted(known_ids - set(profiles))
if missing:
    print("Companies without a profile yet:", ", ".join(missing))
if unmatched_fields:
    print("Fields with no group - add a keyword in data/vocab.json:")
    for field, n in unmatched_fields.most_common():
        print(f"  {n} x {field}")
